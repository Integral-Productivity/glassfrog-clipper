/**
 * Regenerates test/fixtures/compose-cases.json from the TypeScript compose().
 *
 * The fixture is the contract between two implementations of the same
 * function. The Safari extension composes in TypeScript; the Share Extension
 * files natively and composes in Swift, because it never runs the web
 * extension at all. ADR 0004 makes the provenance marker the basis of the
 * triage-survival metric, so an item filed from the share sheet whose headline
 * differs by one character is invisible to that metric while looking perfectly
 * fine in GlassFrog.
 *
 * A golden file is the only thing that catches that. Both suites assert against
 * this file rather than against each other, so neither can drift without a
 * visible diff here.
 *
 * Run deliberately — never as part of `npm test`. A fixture regenerated by the
 * same change it is meant to catch proves nothing.
 */
import { writeFile } from 'node:fs/promises';

import { compose } from '../src/compose.ts';

const page = (over = {}) => ({
  url: 'https://example.org/holacracy',
  title: 'Sensing tensions in practice',
  capturedAt: '2026-08-31T16:00:00.000Z',
  ...over,
});

const CASES = [
  { name: 'bare page, no work type, files as a tension', capture: { page: page() } },
  { name: 'note precedes the evidence', capture: { page: page(), note: 'This contradicts our charter.' } },
  { name: 'selection is evidence after the url', capture: { page: page({ selection: 'a quoted passage' }) } },
  { name: 'note and selection together', capture: { page: page({ selection: 'quoted' }), note: 'my thought' } },
  { name: 'explicit action', capture: { page: page(), workType: 'action', note: 'ring the Lead Link' } },
  { name: 'explicit project carries the url in link as well as the note', capture: { page: page(), workType: 'project' } },
  {
    name: 'a project with no url omits link rather than sending it blank',
    capture: { page: page({ url: '' }), workType: 'project' },
  },
  {
    name: 'a project link is never truncated, however long the url',
    capture: { page: page({ url: `https://example.org/${'q'.repeat(5000)}` }), workType: 'project' },
  },
  { name: 'empty title falls back to the marker alone', capture: { page: page({ title: '' }) } },
  { name: 'whitespace-only title is not a title', capture: { page: page({ title: '   ' }) } },
  {
    name: 'over-long title is truncated but the marker survives whole',
    capture: { page: page({ title: 'x'.repeat(400) }) },
  },
  {
    name: 'astral-plane title truncates on code points, not code units',
    capture: { page: page({ title: '👩‍👩‍👧‍👦'.repeat(120) }) },
  },
  { name: 'empty url and empty title', capture: { page: page({ title: '', url: '' }) } },
  {
    name: 'multi-line selection keeps its newlines',
    capture: { page: page({ selection: 'line one\nline two' }) },
  },
];

const fixture = {
  $comment:
    'Generated by scripts/generate-compose-fixtures.mjs. Asserted by test/compose.test.ts and ' +
    'apple/GlassFrogClipperCore Tests. Regenerate deliberately; a fixture regenerated by the ' +
    'change it is meant to catch proves nothing.',
  cases: CASES.map(({ name, capture }) => ({ name, capture, expected: compose(capture) })),
};

await writeFile('test/fixtures/compose-cases.json', `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`wrote ${fixture.cases.length} compose cases`);
